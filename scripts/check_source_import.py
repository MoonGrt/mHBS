#!/usr/bin/env python3
"""Verify the direct ABI4 import without the parent repository or Git history."""
from __future__ import annotations
import argparse,hashlib,json,re,sys,tarfile,tempfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
DEFAULT=ROOT/'docs/manifests/experiments/image_chain_tree_import_20261021'
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def tokens(text):
    text=re.sub(r'/\*.*?\*/|//[^\n]*','',text,flags=re.S)
    return re.findall(r"[A-Za-z_$][A-Za-z0-9_$]*|\d+'[sS]?[bBoOdDhH][0-9a-fA-F_xXzZ?]+|\d+|[^\s]",text)
def check(archive):
    info=json.loads((archive/'SOURCE.json').read_text())
    assert sha(archive/'upstream.tar.gz')==info['upstream_sha256']
    with tarfile.open(archive/'upstream.tar.gz') as tar:
        original={m.name:tar.extractfile(m).read().decode() for m in tar.getmembers() if m.isfile()}
    def norm(text):
        for a,b in sorted(info['replacements'].items(),key=lambda item:-len(item[0])):text=text.replace(a,b)
        return text
    namespace={};exec(original['scripts/micro_common_partition.py'],namespace)
    common,shell=namespace['partition'](original['rtl/top/mhbs_top.sv'])
    rows={}
    for row in info['production']:
        raw=common if row['mode']=='partition_common' else shell if row['mode']=='partition_shell' else '\n'.join(original[p] for p in row['sources'])
        target=ROOT/row['target'];expected=norm(raw)
        assert tokens(target.read_text())==tokens(expected),row['target']+' differs from controlled upstream mapping'
        assert sha(target)==info['files'][row['target']],row['target']+' hash differs from final freeze'
        rows[row['target']]={'passed':True,'sha256':sha(target),'upstream_sources':row['sources']}
    from model.mHBS import compile_micro
    from model.microcode import ABI,MAGIC,MicroImage
    from model.profiles import SLH_NAMES
    assert ABI==4
    images={}
    with tempfile.TemporaryDirectory() as folder:
        for name in SLH_NAMES:
            image=compile_micro(name);image.write(Path(folder)/name)
            for f in ('program.mem','descriptor.mem'):
                path=ROOT/'tb/vectors'/name/f;data=path.read_bytes()
                assert data==original[f'manifests/micro/images/{name}/{f}'].encode(),str(path)+' original bytes differ'
                assert data==(Path(folder)/name/f).read_bytes(),str(path)+' regenerated bytes differ'
                images[name+'/'+f]=sha(path)
        image=compile_micro('slh_128f')
        for abi in (1,2,3,5):
            desc=list(image.descriptors);desc[0]=(desc[0]&~(31<<27))|(abi<<27)
            try:MicroImage(image.program,tuple(desc)).validate()
            except ValueError:pass
            else:raise AssertionError('Accepted ABI'+str(abi))
    return {'passed':True,'abi':4,'source_commit':info['source_commit'],'production_token_equivalence':rows,'canonical_regenerated_images':images,'rejected_abis':[1,2,3,5],'formal_equivalence_tool':False}

def check_rtl_rejection(folder):
    import subprocess
    folder=folder.resolve();folder.mkdir(parents=True,exist_ok=True)
    bench=folder/'reject.sv'
    bench.write_text("""module reject;
logic clk=0,rst=1;always #5 clk=~clk;
integer abi=1;wire [4:0] descriptor_address;wire [8:0] program_address;
wire [63:0] descriptor_data=descriptor_address==0 ? (64'h4842535000000000|(64'(abi)<<27)) : 64'h2303421603420310;
wire error,busy,done;wire [15:0] error_code;wire out_valid,message_ready,verify_ready;
common #(.PROFILE_ENABLE(0)) dut(.clk,.rst,.program_address,.program_data(64'd0),.descriptor_address,.descriptor_data,
.job_secret_seed(256'd0),.job_secret_prf(256'd0),.job_public_seed(256'd0),.job_randomizer(256'd0),.job_public_root(256'd0),
.job_operation(2'd0),.message_length(7'd0),.verify_valid(1'b0),.verify_ready,.verify_data(256'd0),
.message_data(64'd0),.message_valid(1'b0),.message_ready,.out_valid,.busy,.done,.error,.error_code);
task automatic tick;@(posedge clk);#1;endtask
initial begin
for(integer k=0;k<4;k=k+1)begin
abi=k==3 ? 5 : k+1;rst=1;repeat(3)tick();rst=0;repeat(15)tick();
if(!error || error_code!=16'h3101 || busy || done || out_valid || message_ready || verify_ready || dut.core_released || dut.core.physical_valid)
$fatal(1,"Cross ABI %0d was not rejected atomically",abi);
end
$display("ABI_REJECTION_PASS ABIs=1,2,3,5");$finish;
end
endmodule
""")
    rtl=(ROOT/'sources.txt').read_text().split()
    cmd=['verilator','--binary','--timing','-O2','-j','2','-Wno-fatal','-Wno-WIDTH','-Wno-UNOPTFLAT','--top-module','reject','--Mdir',str(folder/'obj'),*rtl,str(bench)]
    with (folder/'compile.log').open('w') as out:subprocess.run(cmd,cwd=ROOT,stdout=out,stderr=subprocess.STDOUT,check=True)
    with (folder/'run.log').open('w') as out:subprocess.run([str(folder/'obj/Vreject')],cwd=ROOT,stdout=out,stderr=subprocess.STDOUT,check=True)
    assert 'ABI_REJECTION_PASS' in (folder/'run.log').read_text()
    result={'passed':True,'rejected_abis':[1,2,3,5],'no_hash_or_io_before_fault':True,'command':cmd,'files':{name:sha(ROOT/name) for name in rtl},'binary_sha256':sha(folder/'obj/Vreject'),'log_sha256':sha(folder/'run.log')}
    (folder/'results.json').write_text(json.dumps(result,indent=2,sort_keys=True)+'\n');return result

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--rtl-reject',type=Path);p.add_argument('--archive',type=Path,default=DEFAULT);p.add_argument('--out',type=Path,default=ROOT/'build/image-chain-tree/import_check.json');a=p.parse_args()
    result=check(a.archive);result.update(rtl_rejection=check_rtl_rejection(a.rtl_reject)) if a.rtl_reject else None;a.out.parent.mkdir(parents=True,exist_ok=True);a.out.write_text(json.dumps(result,indent=2,sort_keys=True)+'\n');print('SOURCE_IMPORT_PASS',len(result['production_token_equivalence']),'production files;',len(result['canonical_regenerated_images']),'identical images')
if __name__=='__main__':main()
