#!/usr/bin/env python3
"""Generate primitive-only hashlib TREE unit oracles; --check never writes.

This module imports no ISA, compiler, VM, reference algorithm or old macro
interpreter.  A flat layer-by-layer tree is the independent signing oracle.
"""
from __future__ import annotations
import argparse
import hashlib
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
OUTPUT=ROOT/'tb/tree_vectors.svh'
SEED=bytes(range(16));PUBLIC=bytes(range(64,80));EXTERNAL=bytes(range(128,144))
TREE=0xfedcba9876543210
DIGITS=[v for byte in PUBLIC for v in (byte>>4,byte&15)]
CHECKSUM=sum(15-v for v in DIGITS)
DIGITS += [(CHECKSUM>>shift)&15 for shift in (8,4,0)]


def hash_node(layer,domain,leaf,a,b,payload):
    address=b''.join(value.to_bytes(4,'big') for value in
        (layer,0,TREE>>32,TREE&0xffffffff,domain,leaf,a,b))
    return hashlib.shake_256(PUBLIC+address+payload).digest(16)


def ht(height,target,layer):
    row=[];signature=[]
    for leaf in range(1<<height):
        endpoints=[]
        for chain,digit in enumerate(DIGITS):
            value=hash_node(layer,5,leaf,chain,0,SEED)
            if leaf==target and digit==0:signature.append(value)
            for step in range(15):
                value=hash_node(layer,0,leaf,chain,step,value)
                if leaf==target and digit==step+1:signature.append(value)
            endpoints.append(value)
        row.append(hash_node(layer,1,leaf,0,0,b''.join(endpoints)))
    auth=[]
    for level in range(height):
        auth.append(row[(target>>level)^1])
        row=[hash_node(layer,2,0,level+1,index//2,row[index]+row[index+1])
            for index in range(0,len(row),2)]
    return row[0],signature+auth


def fors(height,target,layer,group,leaf):
    row=[];secret=None
    for index in range(1<<height):
        value=hash_node(layer,6,leaf,0,(group<<height)+index,SEED)
        if index==target:secret=value
        row.append(hash_node(layer,3,leaf,0,(group<<height)+index,value))
    auth=[]
    for level in range(height):
        auth.append(row[(target>>level)^1])
        row=[hash_node(layer,3,leaf,level+1,(group<<(height-level-1))+index//2,
            row[index]+row[index+1]) for index in range(0,len(row),2)]
    return row[0],[secret]+auth


def cases():
    records=[]
    def add(kind,mode,flags,hp,a,layer,leaf,target,group,root,inputs,outputs,hashes,permutations):
        records.append(dict(kind=kind,mode=mode,flags=flags,hp=hp,a=a,layer=layer,leaf=leaf,
            target=target,group=group,root=root,inputs=inputs,outputs=outputs,
            hash_count=hashes,permutation_count=permutations,input_count=len(inputs),output_count=len(outputs)))
    root,sig=ht(1,0,0)
    add(0,0,0,1,2,0,1,0,1,root,[],[],1123,1131)
    add(0,1,0,1,2,0,1,0,1,root,[],sig,1123,1131)
    suffix=sum(15-digit for digit in DIGITS)
    add(0,2,0,1,2,0,0,0,1,root,sig,[],suffix+2,suffix+6)
    _,sig_top=ht(1,1,21)
    prefix=sum(1+digit for digit in DIGITS)
    add(0,1,1,1,2,21,1,1,1,EXTERNAL,[],sig_top,560+1+prefix,560+5+prefix)
    root,sig=fors(2,1,0,1,1)
    add(1,1,0,1,2,0,1,1,1,root,[],sig,11,11)
    add(1,2,0,1,2,0,1,1,1,root,sig,[],3,3)
    # Height-14 verification only needs one secret and fourteen siblings.
    sig=[bytes((index*17+offset*7+3)&255 for offset in range(16)) for index in range(15)]
    index=(1<<14)-1;root=hash_node(0,3,1,0,(1<<14)+index,sig[0])
    for level,sibling in enumerate(sig[1:],1):
        left,right=(sibling,root) if index&1 else (root,sibling)
        index>>=1;root=hash_node(0,3,1,level,(1<<(14-level))+index,left+right)
    add(1,2,0,1,14,0,1,(1<<14)-1,1,root,sig,[],15,15)
    return records


def render_slh():
    data=cases();rows=['// Generated by scripts/generate_tree_vectors.py; independent hashlib only.',
        '// Node constants contain n bytes in the least significant bytes, little endian.',
        f'localparam integer TREE_CASES={len(data)};']
    for field in ('kind','mode','flags','hp','a','layer','leaf','target','group',
                  'hash_count','permutation_count','input_count','output_count'):
        rows += [f'function automatic integer tree_case_{field}(input integer which);',
            '    case(which)',*[f'        {i}:tree_case_{field}={case[field]};' for i,case in enumerate(data)],
            f'        default:tree_case_{field}=-1;', '    endcase','endfunction']
    rows += ['function automatic [63:0] tree_case_tree(input integer which);',
        f"    tree_case_tree=64'h{TREE:016x};",'endfunction',
        'function automatic [255:0] tree_case_root(input integer which);','    case(which)']
    for i,case in enumerate(data):rows.append(f"        {i}:tree_case_root=256'h{int.from_bytes(case['root'],'little'):064x};")
    rows += ["        default:tree_case_root='0;",'    endcase','endfunction']
    for name in ('input','output'):
        rows += [f'function automatic [255:0] tree_case_{name}(input integer which,index);','    case(which)']
        for i,case in enumerate(data):
            rows += [f'        {i}:begin','            case(index)']
            for j,node in enumerate(case[name+'s']):rows.append(
                f"                {j}:tree_case_{name}=256'h{int.from_bytes(node,'little'):064x};")
            rows += [f"                default:tree_case_{name}='0;",'            endcase','        end']
        rows += [f"        default:tree_case_{name}='0;",'    endcase','endfunction']
    return '\n'.join(rows)+'\n'


# The stateful verifier oracle is independently assembled from hashlib only.
# In particular it imports no algorithm model, ISA, compiler or VM helper.
def stateful_cases():
    public=bytes(range(64,96));identifier=bytes(range(160,176))
    digits=[v for byte in public for v in (byte>>4,byte&15)]
    checksum=sum(15-v for v in digits)
    digits += [(checksum>>shift)&15 for shift in (8,4,0)]
    records=[]
    for family,height,q,profile in (('xmss',10,0,8),('xmss',16,65535,9),
        ('xmss',20,1048575,10),('lms',10,1,11),('lms',15,32767,12),('lms',20,1048575,13)):
        inputs=[bytes((i*13+j*7+0x31)&255 for j in range(32)) for i in range(67)]
        inputs += [bytes((i*17+j*3+0x91)&255 for j in range(32)) for i in range(height)]
        hashes=permutations=0
        def shake(data):
            nonlocal hashes,permutations
            hashes+=1;permutations+=len(data)//136+1
            return hashlib.shake_256(data).digest(32)
        def adrs(kind,leaf,a,b,keymask):
            return b''.join(value.to_bytes(4,'big') for value in (0,0,0,kind,leaf,a,b,keymask))
        def prf(kind,leaf,a,b,keymask):
            return shake((3).to_bytes(32,'big')+public+adrs(kind,leaf,a,b,keymask))
        def xmss_f(value,chain,step):
            key=prf(0,q,chain,step,0);mask=prf(0,q,chain,step,1)
            return shake(bytes(32)+key+bytes(x^y for x,y in zip(value,mask)))
        def xmss_h(left,right,kind,leaf,a,b):
            key=prf(kind,leaf,a,b,0);m0=prf(kind,leaf,a,b,1);m1=prf(kind,leaf,a,b,2)
            return shake((1).to_bytes(32,'big')+key+bytes(x^y for x,y in zip(left,m0))+bytes(x^y for x,y in zip(right,m1)))
        row=[]
        for i,digit in enumerate(digits):
            value=inputs[i]
            for j in range(digit,15):
                value=xmss_f(value,i,j) if family=='xmss' else shake(identifier+q.to_bytes(4,'big')+i.to_bytes(2,'big')+bytes([j])+value)
            row.append(value)
        if family=='xmss':
            level=0
            while len(row)>1:
                row=[xmss_h(row[i],row[i+1],1,q,level,i//2) if i+1<len(row) else row[i] for i in range(0,len(row),2)]
                level+=1
            value=row[0];index=q
            for level,sibling in enumerate(inputs[67:]):
                left,right=(sibling,value) if index&1 else (value,sibling);index>>=1
                value=xmss_h(left,right,2,0,level,index)
        else:
            k=shake(identifier+q.to_bytes(4,'big')+bytes.fromhex('8080')+b''.join(row))
            index=(1<<height)+q;value=shake(identifier+index.to_bytes(4,'big')+bytes.fromhex('8282')+k)
            for sibling in inputs[67:]:
                left,right=(sibling,value) if index&1 else (value,sibling);index>>=1
                value=shake(identifier+index.to_bytes(4,'big')+bytes.fromhex('8383')+left+right)
        records.append(dict(profile=profile,height=height,q=q,root=value,inputs=inputs,
            hash_count=hashes,permutation_count=permutations))
    return records


def render_stateful():
    data=stateful_cases();rows=['// Six stateful full-height Verify oracles, hashlib only.',
        f'localparam integer STATEFUL_TREE_CASES={len(data)};']
    for field in ('profile','height','q','hash_count','permutation_count'):
        rows += [f'function automatic integer stateful_tree_{field}(input integer which);','    case(which)',
            *[f'        {i}:stateful_tree_{field}={case[field]};' for i,case in enumerate(data)],
            f'        default:stateful_tree_{field}=-1;','    endcase','endfunction']
    rows += ['function automatic [255:0] stateful_tree_root(input integer which);','    case(which)',
        *[f"        {i}:stateful_tree_root=256'h{int.from_bytes(case['root'],'little'):064x};" for i,case in enumerate(data)],
        "        default:stateful_tree_root='0;",'    endcase','endfunction',
        'function automatic [255:0] stateful_tree_input(input integer which,index);','    case(which)']
    for i,case in enumerate(data):
        rows += [f'        {i}:begin','            case(index)',
            *[f"                {j}:stateful_tree_input=256'h{int.from_bytes(node,'little'):064x};" for j,node in enumerate(case['inputs'])],
            "                default:stateful_tree_input='0;",'            endcase','        end']
    rows += ["        default:stateful_tree_input='0;",'    endcase','endfunction']
    return '\n'.join(rows)+'\n'


def render():
    return render_slh()+render_stateful()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out',type=Path,default=OUTPUT)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args();expected=render()
    if args.check:
        if args.out.read_text()!=expected:raise ValueError('TREE fixture differs from independent hashlib oracle')
        print('MICRO_TREE_FIXTURE_PASS slh_cases=7 stateful_cases=6')
    else:
        args.out.parent.mkdir(parents=True,exist_ok=True);args.out.write_text(expected)
        print('MICRO_TREE_FIXTURE_GENERATED slh_cases=7 stateful_cases=6',args.out)


if __name__=='__main__':main()
